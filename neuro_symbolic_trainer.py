def main(argv: Optional[Sequence[str]] = None) -> int:
    args = build_cli().parse_args(argv)

    if args.self_test:
        self_test()
        print("SELF_TEST_PASS")
        return 0

    if args.architecture:
        print(json.dumps(architecture_spec(), indent=2, ensure_ascii=False))
        if not args.data:
            return 0

    builder = SymbolicBatchBuilder()
    examples = (
        builder.load_jsonl(args.data)
        if args.data
        else make_demo_dataset()
    )

    vocabulary = sorted({
        (example.target or "unknown").strip().lower()
        for example in examples
    })
    if not vocabulary:
        vocabulary = ["unknown"]

    model = ReferenceNeuroSymbolicModel(
        vocabulary=vocabulary,
        seed=42,
    )
    config = TrainerConfig(
        epochs=args.epochs,
        learning_rate=args.lr,
    )
    trainer = ReferenceTrainer(
        model,
        config,
    )
    state = trainer.train(
        examples,
        checkpoint_dir=args.checkpoint_dir,
    )

    print(
        render_training_summary(
            state,
            model,
        )
    )

    return 0


if __name__ == "__main__":
    main()
