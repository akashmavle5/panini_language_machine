def save_jsonl(
    examples: Sequence[TrainingExample],
    path: str | Path,
) -> Path:
    destination = Path(path)
    destination.parent.mkdir(parents=True, exist_ok=True)
    with destination.open("w", encoding="utf-8") as handle:
        for example in examples:
            handle.write(
                json.dumps(
                    example.to_dict(),
                    ensure_ascii=False,
                )
                + "\n"
            )
    return destination


def make_demo_dataset() -> List[TrainingExample]:
    builder = SymbolicBatchBuilder()
    pairs = [
        ("Rama reads the book.", "book"),
        ("Rama writes with a pen.", "pen"),
        ("Rama gives a book to Sita.", "sita"),
        ("Rama builds a book with a knife.", "book"),
        ("Rama writes a book in Mumbai.", "book"),
    ]
    return [
        builder.from_text(text, target=target)
        for text, target in pairs
    ]


