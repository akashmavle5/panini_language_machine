# 7. Optional PyTorch attention module
# ============================================================================

class SymbolicAttentionAdapter:
    """Optional PyTorch module for adding learnable symbolic bias."""

    def __init__(self, initial_scale: float = 1.0) -> None:
        try:
            import torch
            import torch.nn as nn
        except ImportError as exc:
            raise RuntimeError(
                "PyTorch is required for SymbolicAttentionAdapter"
            ) from exc

        self.torch = torch
        self.nn = nn
        self.module = nn.Module()
        self.scale = nn.Parameter(
            torch.tensor(float(initial_scale))
        )

    def parameters(self):
        return [self.scale]

    def forward(self, logits: Any, symbolic_bias: Any) -> Any:
        bias = symbolic_bias
        if bias.ndim == 2:
            bias = bias.unsqueeze(0).unsqueeze(0)
        elif bias.ndim == 3:
            bias = bias.unsqueeze(1)
        return logits + self.scale * bias


