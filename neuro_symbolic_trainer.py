"""
neuro_symbolic_trainer.py
=========================

Panini Language Machine — Neuro-Symbolic Trainer

File 11/14.

Purpose
-------
Turn the symbolic representation produced by paninian_english_llm.py into a
trainable neural side-channel.  The trainer supports three levels:

1. Pure-Python reference training for architectural tests.
2. Optional PyTorch symbolic-bias training.
3. A Transformer-compatible batch contract for future full LLM training.

The central hypothesis is:

    token representation + Paninian structural representation
                              ->
                    neural prediction

and, for attention-based models:

    attention logits + learned/scaled symbolic bias -> attention weights

This file deliberately does not claim to be a production LLM trainer. It is
a research scaffold with inspectable losses, symbolic gates, checkpointing,
and deterministic self-tests.

The trainer can consume either:
    - Paninian English representations generated by File 10, or
    - lightweight JSON records containing input/target text and symbolic bias.

No PyTorch installation is required for the reference path.
"""

