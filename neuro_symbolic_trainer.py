# 11. Self-test
# ============================================================================

def self_test() -> None:
    # Numerical tests.
    probabilities = softmax([0.0, 1.0, 2.0])
    assert len(probabilities) == 3
    assert abs(sum(probabilities) - 1.0) < 1e-9
    assert probabilities[2] > probabilities[1] > probabilities[0]

    loss = cross_entropy(probabilities, 2)
    assert loss > 0

    # Symbolic preprocessing.
    builder = SymbolicBatchBuilder()
    example = builder.from_text(
        "Rama reads the book.",
        target="book",
    )

    assert example.text == "Rama reads the book."
    assert example.symbolic_bias is not None
    assert len(example.symbolic_bias) > 0

    # Reference model/training.
    vocabulary = [
        "book",
        "pen",
        "sita",
        "mumbai",
    ]
    model = ReferenceNeuroSymbolicModel(
        vocabulary,
        seed=7,
    )
    config = TrainerConfig(
        epochs=3,
        learning_rate=0.02,
        checkpoint_every=3,
        seed=7,
    )
    trainer = ReferenceTrainer(model, config)
    dataset = make_demo_dataset()
    state = trainer.train(dataset)

    assert state.epoch == 3
    assert state.step == 15
    assert len(state.history) == 3
    assert math.isfinite(state.best_loss)

    # Checkpoint round-trip existence/content.
    checkpoint = Path("_panini_test_checkpoint.json")
    try:
        trainer.save_checkpoint(checkpoint)
        assert checkpoint.exists()
        payload = json.loads(
            checkpoint.read_text(encoding="utf-8")
        )
        assert payload["format"].startswith(
            "panini_neuro_symbolic_reference"
        )
        assert "model" in payload
    finally:
        if checkpoint.exists():
            checkpoint.unlink()

    # Attention-bias integration.
    logits = [
        [0.0, 0.0],
        [0.0, 0.0],
    ]
    bias = [
        [0.0, 4.0],
        [2.0, 0.0],
    ]
    combined = matrix_add(logits, bias)
    attention = row_softmax(combined)
    assert attention[0][1] > attention[0][0]
    assert attention[1][0] > attention[1][1]

    mass = attention_mass_on_symbolic_edges(
        attention,
        bias,
    )
    assert 0.0 <= mass <= 1.0

    # Architecture contract.
    spec = architecture_spec()
    assert "architecture" in spec
    assert "data_flow" in spec
    assert len(spec["data_flow"]) >= 5

    # JSONL helper.
    jsonl = Path("_panini_test.jsonl")
    try:
        save_jsonl(dataset[:2], jsonl)
        loaded = builder.load_jsonl(jsonl)
        assert len(loaded) == 2
        assert loaded[0].text == dataset[0].text
    finally:
        if jsonl.exists():
            jsonl.unlink()


