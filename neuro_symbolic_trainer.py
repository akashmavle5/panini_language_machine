# 3. Symbolic preprocessing
# ============================================================================

class SymbolicBatchBuilder:
    """Create TrainingExample objects from File 10 representations."""

    def __init__(self, analyzer: Optional[Any] = None) -> None:
        self.analyzer = analyzer
        if self.analyzer is None and VyakaranaGraphAutomata is not None:
            self.analyzer = VyakaranaGraphAutomata()

    def from_text(
        self,
        text: str,
        target: Optional[str] = None,
    ) -> TrainingExample:
        if self.analyzer is None:
            raise RuntimeError(
                "paninian_english_llm.py is required for text-to-symbolic preprocessing"
            )

        representation = self.analyzer.analyze(text)
        return TrainingExample(
            text=text,
            target=target,
            symbolic_bias=representation["Structural_Bias"],
            metadata={
                "action_engine": representation["Action_Engine"],
                "action_engine_index": representation["Action_Engine_Index"],
                "bindings": representation["Bindings"],
                "missing_required_roles": representation["Missing_Required_Roles"],
                "complete_required_frame": representation["Complete_Required_Frame"],
                "atoms": representation["Atoms"],
            },
        )

    def from_json_record(self, record: Mapping[str, Any]) -> TrainingExample:
        text = str(record.get("text") or record.get("input") or "")
        if not text:
            raise ValueError("training record has no text/input field")
        target = record.get("target")
        bias = record.get("symbolic_bias")
        if bias is None:
            representation = self.from_text(text, target=target)
            return representation
        return TrainingExample(
            text=text,
            target=None if target is None else str(target),
            symbolic_bias=[list(map(float, row)) for row in bias],
            metadata=dict(record.get("metadata") or {}),
        )

    def load_jsonl(self, path: str | Path) -> List[TrainingExample]:
        examples: List[TrainingExample] = []
        with Path(path).open("r", encoding="utf-8") as handle:
            for line_number, line in enumerate(handle, start=1):
                line = line.strip()
                if not line:
                    continue
                try:
                    record = json.loads(line)
                    examples.append(self.from_json_record(record))
                except Exception as exc:
                    raise ValueError(
                        f"invalid JSONL record at line {line_number}: {exc}"
                    ) from exc
        return examples


# ============================================================================
# 4. Reference symbolic model
# ============================================================================

class ReferenceNeuroSymbolicModel:
    """
    Tiny differentiable-by-hand model used to validate the architecture.

    It learns a scalar symbolic gate and a set of token-class logits.
    This is NOT intended to compete with a Transformer. It makes the training
    mechanics visible and testable before adding a full neural backbone.
    """

    def __init__(
        self,
        vocabulary: Sequence[str],
        seed: int = 42,
    ) -> None:
        self.vocabulary = list(vocabulary)
        self.index = {token: i for i, token in enumerate(self.vocabulary)}
        rng = random.Random(seed)
        self.bias_gate = 0.5
        self.token_bias = [
            rng.uniform(-0.05, 0.05)
            for _ in self.vocabulary
        ]

    def logits(
        self,
        base_logits: Sequence[float],
        symbolic_score: float,
    ) -> List[float]:
        if len(base_logits) != len(self.vocabulary):
            raise ValueError("base logits and vocabulary have different sizes")
        return [
            float(base) + self.token_bias[i] + self.bias_gate * symbolic_score
            for i, base in enumerate(base_logits)
        ]

    def predict(
        self,
        base_logits: Sequence[float],
        symbolic_score: float,
    ) -> Tuple[int, List[float]]:
        logits = self.logits(base_logits, symbolic_score)
        probabilities = softmax(logits)
        return argmax(probabilities), probabilities


# ============================================================================
# 5. Reference trainer
# ============================================================================

class ReferenceTrainer:
    """Train the small reference model with explicit scalar updates."""

    def __init__(
        self,
        model: ReferenceNeuroSymbolicModel,
        config: Optional[TrainerConfig] = None,
    ) -> None:
        self.model = model
        self.config = config or TrainerConfig()
        self.state = TrainingState()

    @staticmethod
    def symbolic_score(example: TrainingExample) -> float:
        if not example.symbolic_bias:
            return 0.0
        non_zero = [
            abs(value)
            for row in example.symbolic_bias
            for value in row
            if abs(value) > 1e-12
        ]
        if not non_zero:
            return 0.0
        return min(1.0, sum(non_zero) / (len(non_zero) * 5.0))

    def _target_index(self, example: TrainingExample) -> int:
        target = (example.target or "").strip().lower()
        if target in self.model.index:
            return self.model.index[target]

        # Deterministic fallback: hash target/text into the toy vocabulary.
        source = target or example.text
        return int.from_bytes(source.encode("utf-8"), "little") % len(self.model.vocabulary)

    def _base_logits(self, example: TrainingExample) -> List[float]:
        # A deterministic pseudo-feature extractor. The real LLM replaces this
        # with hidden states from a neural backbone.
        digest = sum(ord(char) for char in example.text)
        return [
            math.sin(digest * 0.001 + i) * 0.1
            for i in range(len(self.model.vocabulary))
        ]

    def train_example(self, example: TrainingExample) -> Tuple[float, float, int]:
        base = self._base_logits(example)
        symbolic = self.symbolic_score(example) * self.config.symbolic_bias_scale
        target = self._target_index(example)

        logits = self.model.logits(base, symbolic * self.model.bias_gate)
        probabilities = softmax(logits)
        loss = cross_entropy(probabilities, target)

        # Derivative of CE w.r.t. the shared symbolic gate. Since the symbolic
        # score is a scalar added equally to every class in this toy model,
        # its gradient is zero. We therefore use a contrastive symbolic score
        # below: positive symbolic evidence is treated as a target-dependent
        # prior. This keeps the toy trainer mathematically meaningful.
        symbolic_prior = [
            symbolic if i == target else 0.0
            for i in range(len(probabilities))
        ]
        prior_logits = [
            logits[i] + symbolic_prior[i]
            for i in range(len(logits))
        ]
        prior_probabilities = softmax(prior_logits)
        symbolic_loss = cross_entropy(prior_probabilities, target)

        gradient = [
            probability - (1.0 if i == target else 0.0)
            for i, probability in enumerate(prior_probabilities)
        ]

        lr = self.config.learning_rate
        for i in range(len(self.model.token_bias)):
            self.model.token_bias[i] -= lr * clip(
                gradient[i],
                self.config.gradient_clip,
            )

        gate_gradient = -symbolic * max(0.0, 1.0 - prior_probabilities[target])
        self.model.bias_gate -= lr * clip(
            gate_gradient,
            self.config.gradient_clip,
        )

        predicted = argmax(prior_probabilities)
        return loss, symbolic_loss, int(predicted == target)

    def train(
        self,
        examples: Sequence[TrainingExample],
        checkpoint_dir: Optional[str | Path] = None,
    ) -> TrainingState:
        if not examples:
            raise ValueError("training set is empty")

        for epoch in range(1, self.config.epochs + 1):
            losses: List[float] = []
            symbolic_losses: List[float] = []
            correct = 0
            attention_masses: List[float] = []

            for example in examples:
                loss, symbolic_loss, is_correct = self.train_example(example)
                losses.append(loss)
                symbolic_losses.append(symbolic_loss)
                correct += is_correct
                self.state.step += 1

                if example.symbolic_bias:
                    attention = row_softmax(
                        example.symbolic_bias
                    )
                    attention_masses.append(
                        attention_mass_on_symbolic_edges(
                            attention,
                            example.symbolic_bias,
                        )
                    )

            metric = TrainingMetrics(
                epoch=epoch,
                loss=sum(losses) / len(losses),
                symbolic_loss=sum(symbolic_losses) / len(symbolic_losses),
                baseline_loss=sum(losses) / len(losses),
                accuracy=correct / len(examples),
                symbolic_attention_mass=(
                    sum(attention_masses) / len(attention_masses)
                    if attention_masses else 0.0
                ),
            )

            self.state.epoch = epoch
            self.state.history.append(metric)
            self.state.best_loss = min(
                self.state.best_loss,
                metric.loss,
            )

            if checkpoint_dir and (
                epoch % self.config.checkpoint_every == 0
                or epoch == self.config.epochs
            ):
                self.save_checkpoint(
                    Path(checkpoint_dir) / f"checkpoint_epoch_{epoch}.json"
                )

        return self.state

    def save_checkpoint(self, path: str | Path) -> Path:
        destination = Path(path)
        destination.parent.mkdir(parents=True, exist_ok=True)
        payload = {
            "format": "panini_neuro_symbolic_reference_checkpoint_v1",
            "config": self.config.to_dict(),
            "state": self.state.to_dict(),
            "model": {
                "vocabulary": self.model.vocabulary,
                "bias_gate": self.model.bias_gate,
                "token_bias": self.model.token_bias,
            },
        }
        destination.write_text(
            json.dumps(payload, indent=2, ensure_ascii=False),
            encoding="utf-8",
        )
        return destination


