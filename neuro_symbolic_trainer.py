@dataclass
class TransformerBatch:
    input_ids: Any
    attention_mask: Any
    symbolic_bias: Any
    labels: Any
    metadata: Dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "input_ids": self.input_ids,
            "attention_mask": self.attention_mask,
            "symbolic_bias": self.symbolic_bias,
            "labels": self.labels,
            "metadata": self.metadata,
        }


def build_transformer_batch(
    examples: Sequence[TrainingExample],
    tokenizer: Any,
    pad_token_id: int = 0,
) -> TransformerBatch:
    """
    Build a generic batch from a HuggingFace-compatible tokenizer.

    tokenizer is intentionally injected. This keeps File 11 independent of a
    specific tokenizer/model family.
    """
    if not examples:
        raise ValueError("examples cannot be empty")

    texts = [example.text for example in examples]
    encoded = tokenizer(
        texts,
        padding=True,
        truncation=True,
        return_tensors="pt",
    )

    input_ids = encoded["input_ids"]
    attention_mask = encoded["attention_mask"]
    batch_size, sequence_length = input_ids.shape

    # Symbolic bias matrices are created over source tokens. A real tokenizer
    # may split words into subwords; mapping from word indices to subword spans
    # is therefore left as an explicit future extension instead of silently
    # assuming 1:1 alignment.
    symbolic_bias = []
    for example in examples:
        if example.symbolic_bias is None:
            symbolic_bias.append([
                [0.0] * sequence_length
                for _ in range(sequence_length)
            ])
            continue

        source = example.symbolic_bias
        resized = [
            row[:sequence_length]
            + [0.0] * max(0, sequence_length - len(row))
            for row in source[:sequence_length]
        ]
        while len(resized) < sequence_length:
            resized.append([0.0] * sequence_length)
        symbolic_bias.append(resized)

    try:
        import torch
        symbolic_bias_tensor = torch.tensor(
            symbolic_bias,
            dtype=torch.float32,
            device=input_ids.device,
        ).unsqueeze(1)
    except ImportError:
        symbolic_bias_tensor = symbolic_bias

    labels = input_ids.clone() if hasattr(input_ids, "clone") else input_ids

    return TransformerBatch(
        input_ids=input_ids,
        attention_mask=attention_mask,
        symbolic_bias=symbolic_bias_tensor,
        labels=labels,
        metadata={
            "batch_size": batch_size,
            "sequence_length": sequence_length,
            "symbolic_alignment": "conservative_word_to_token_crop",
            "pad_token_id": pad_token_id,
        },
    )


