def render_training_summary(
    state: TrainingState,
    model: ReferenceNeuroSymbolicModel,
) -> str:
    lines = [
        "=" * 96,
        "PANINI NEURO-SYMBOLIC TRAINER",
        "=" * 96,
        f"epochs: {state.epoch}",
        f"steps: {state.step}",
        f"best loss: {state.best_loss:.6f}",
        f"learned symbolic gate: {model.bias_gate:.6f}",
        "",
        "TRAINING HISTORY",
        "-" * 96,
    ]

    for metric in state.history:
        lines.append(
            f"epoch={metric.epoch:03d} "
            f"loss={metric.loss:.6f} "
            f"symbolic_loss={metric.symbolic_loss:.6f} "
            f"accuracy={metric.accuracy:.3f} "
            f"symbolic_attention_mass={metric.symbolic_attention_mass:.3f}"
        )

    return "\n".join(lines)


